import test from 'node:test';
import assert from 'node:assert/strict';
import { groupClients, packageStatus, filterClients, sortClients } from '../src/admin/clients.js';

const asOf = '2026-09-19';
const client = { id: 'google:one', client_name: 'Website Buyer', phone: '+85297919712', email: 'buyer@example.test', version: 1 };
const website = { id: 'website:order-1', source: 'website', client_id: 'google:one', client_name: 'Website Buyer', phone: '+85297919712', email: 'buyer@example.test',
  package_name: '10-class pack - 1:1', credits_left: 10, total_credits: 10, purchase_amount_hkd: 9000, remaining_value_hkd: null,
  purchase_date: '2026-09-18', expiry_date: null, days_to_expiry: null, validity_months: 6, payment_status: 'paid', source_row: null, duplicate_of_row: null, mindbody: null };
const studio = { id: 'row-1', client_id: 'google:one', client_name: 'Website Buyer', package_name: 'Example Private 5', credits_left: 2, total_credits: 5, purchase_date: '2026-09-01', expiry_date: '2026-09-25', days_to_expiry: 6, source_row: 2, duplicate_of_row: null };

test('website purchases count as packages with credits and stay in date until a first class sets an expiry', () => {
  const [grouped] = groupClients([website], [client]);
  assert.equal(grouped.packages.length, 1); assert.equal(grouped.credits, 10); assert.equal(grouped.totalCredits, 10); assert.equal(grouped.nextExpiry, null);
  assert.equal(packageStatus([website], asOf), 'In date');
  assert.equal(packageStatus([{ ...website, credits_left: 0, payment_status: 'refunded' }], asOf), 'No credits');
  assert.equal(packageStatus([{ ...website, credits_left: null }], asOf), 'No credits'); // usage lives in the ledger; nothing is invented
  assert.equal(groupClients([{ ...website, credits_left: null }], [client])[0].credits, 0);
  assert.equal(filterClients([grouped], '', 'expiring', asOf).length, 0); // no expiry is not "expiring"
  assert.equal(filterClients([grouped], '10-class', 'all', asOf).length, 1);
});

test('studio and website packages combine per client and sort by real expiry only', () => {
  const [grouped] = groupClients([studio, website], [client]);
  assert.equal(grouped.packages.length, 2); assert.equal(grouped.credits, 12); assert.equal(grouped.nextExpiry, '2026-09-25');
  assert.equal(packageStatus(grouped.packages, asOf), 'Expires within 30 days');
  assert.equal(filterClients([grouped], '', 'expiring', asOf).length, 1);
  const other = groupClients([website], [{ ...client, id: 'google:two', client_name: 'Another Buyer' }, client]);
  assert.deepEqual(sortClients(other, 'credits', 'desc', asOf).map(c => c.id), ['google:one', 'google:two']);
});
